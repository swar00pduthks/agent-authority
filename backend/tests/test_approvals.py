from __future__ import annotations

import hashlib
import hmac
import json

import pytest
from fastapi.testclient import TestClient

from agent_authority.api.main import create_app
from agent_authority.sdk import Authority, CallbackTransport, Dataset
from agent_authority.service import authority_chain
from agent_authority.storage.memory import MemoryStore

REPO = Dataset("git://github.com/northwind-apps", "kyc-review-queue")


@pytest.fixture
def env(monkeypatch):
    monkeypatch.setenv("AUTHORITY_GITHUB_WEBHOOK_SECRET", "gh-secret")
    monkeypatch.setenv("AUTHORITY_GITLAB_WEBHOOK_TOKEN", "gl-token")
    app = create_app(MemoryStore())
    aa = Authority(transport=CallbackTransport(lambda ev: app.state.ingest([ev])), namespace="appbuilder/kyc")
    with aa.session("build: KYC review queue", on_behalf_of="user:aisha.khan") as s:
        with aa.agent("coder", owner="app-builder-platform"):
            with aa.tool("open_pull_request", side_effecting=True, outputs=[REPO]) as pr:
                pr.allow("human-review-required")
    return TestClient(app), app.state.store, s, pr


def chain(store, pr):
    return authority_chain(store, pr.run_id)


def test_review_required_without_approval_is_flagged(env):
    _, store, _, pr = env
    c = chain(store, pr)
    assert c["verdict"] == "warn"
    assert any(ch["check"] == "human approval" for ch in c["hops"][-1]["checks"])


def test_api_approval_closes_the_chain_at_a_person(env):
    client, store, s, pr = env
    r = client.post("/api/authority/approvals", json={
        "session_id": s.run_id, "approver": "user:priya.sharma", "decision": "approved", "provider": "github",
        "reference": "PR #42", "repository": {"namespace": REPO.namespace, "name": REPO.name}})
    assert r.status_code == 201
    c = chain(store, pr)
    last = c["hops"][-1]
    assert c["verdict"] == "pass"
    assert last["kind"] == "approval" and last["principal"] == "user:priya.sharma"
    assert "github PR #42" in last["checks"][0]["detail"]
    # the approval also joined the session's integrity chain
    assert client.get(f"/api/authority/sessions/{s.run_id}/integrity").json()["status"] == "intact"


def test_github_webhook_signed_merge(env):
    client, store, s, pr = env
    payload = {"action": "closed", "repository": {"name": REPO.name, "owner": {"login": "northwind-apps"}},
               "pull_request": {"number": 42, "merged": True, "merged_by": {"login": "octo-reviewer"},
                                "merged_at": "2026-10-04T12:00:00Z", "html_url": "https://github.com/x/y/pull/42",
                                "body": f"Generated by the app builder.\n\n{s.pr_marker}"}}
    body = json.dumps(payload).encode()
    bad = client.post("/api/authority/webhooks/github", content=body,
                      headers={"x-github-event": "pull_request", "x-hub-signature-256": "sha256=deadbeef"})
    assert bad.status_code == 401
    sig = "sha256=" + hmac.new(b"gh-secret", body, hashlib.sha256).hexdigest()
    ok = client.post("/api/authority/webhooks/github", content=body,
                     headers={"x-github-event": "pull_request", "x-hub-signature-256": sig})
    assert ok.json()["recorded"] is True
    last = chain(store, pr)["hops"][-1]
    assert last["principal"] == "github:octo-reviewer" and last["status"] == "pass"


def test_gitlab_changes_requested_then_approved(env):
    client, store, s, pr = env
    def mr(action, user):
        return {"object_kind": "merge_request", "user": {"username": user},
                "project": {"path_with_namespace": "northwind-apps/kyc-review-queue",
                            "web_url": "https://gitlab.example.com/northwind-apps/kyc-review-queue"},
                "object_attributes": {"iid": 7, "action": action, "description": s.pr_marker,
                                      "url": "https://gitlab.example.com/mr/7"}}
    h = {"x-gitlab-token": "gl-token"}
    assert client.post("/api/authority/webhooks/gitlab", json=mr("unapproved", "risk.lead"), headers=h).json()["recorded"]
    assert chain(store, pr)["verdict"] == "fail"  # explicitly rejected, nothing later
    assert client.post("/api/authority/webhooks/gitlab", json=mr("approved", "risk.lead"), headers=h).json()["recorded"]
    c = chain(store, pr)
    assert c["verdict"] == "pass"
    assert [hp["kind"] for hp in c["hops"]][-2:] == ["approval", "approval"]
    assert client.post("/api/authority/webhooks/gitlab", json=mr("approved", "x"), headers={}).status_code == 401


def test_unlinked_pr_is_ignored(env):
    client, *_ = env
    r = client.post("/api/authority/webhooks/gitlab", json={"object_kind": "merge_request",
                    "object_attributes": {"action": "merge", "description": "no marker"}},
                    headers={"x-gitlab-token": "gl-token"})
    assert r.json()["recorded"] is False
